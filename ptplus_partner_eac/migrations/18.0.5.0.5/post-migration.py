def migrate(cr, version):
    env = api.Environment(cr, SUPERUSER_ID, {})

    partner_eacs = env["l10n_pt.res.partner.eac"].search([])

    for partner_eac in partner_eacs:
        eac_code = partner_eac.eac_id.type + ":" + partner_eac.eac_id.code
        if eac_code in codes_to_remove:
            new_code = False
            for i in range(len(eac_code), 1, -1):
                new_code = eac_code[:i]
                if new_code not in codes_to_remove:
                    break

            new_code_split = new_code.split(":")
            eac_id = env["l10n_pt.company.eac"].search(
                [("code", "=", new_code_split[1]), ("type", "=", new_code_split[0])]
            )
            partner_eac.eac_id = eac_id
